import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = fileURLToPath(new URL('../../', import.meta.url));
const edition = JSON.parse(fs.readFileSync(path.join(root, 'data/news/personal-editorials.json')))
  .editions.find(item => item.analysis_id === 'woek-personal-a5af43a9262df8f2');
const route = `wirkungsticker/analyse/${edition.slug}/index.html`;
const approvedHtml = fs.readFileSync(path.join(root, route), 'utf8');

function check({ html = approvedHtml, source = edition, target = route } = {}) {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'editorial-privacy-'));
  try {
    const output = path.join(temporary, '_site', target);
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, html);
    if (source) {
      fs.mkdirSync(path.join(temporary, 'data/news'), { recursive: true });
      fs.writeFileSync(path.join(temporary, 'data/news/personal-editorials.json'), JSON.stringify({ editions: [source] }));
    }
    return spawnSync(process.execPath, [path.join(root, 'scripts/quality/check-public-artifact-privacy.mjs')],
      { cwd: temporary, encoding: 'utf8' });
  } finally { fs.rmSync(temporary, { recursive: true, force: true }); }
}

test('the exact approved AI review retains its public product and source names', () => {
  const result = check();
  assert.equal(result.status, 0, result.stderr);
});
test('additional production references in the same approved page remain blocked', () => {
  for (const note of ['Created with Claude', 'Generated by ChatGPT', 'How people ask Claude for personal guidance',
    'https://www.anthropic.com/research/claude-personal-guidance']) {
    assert.equal(check({ html: approvedHtml + `<p>${note}</p>` }).status, 1);
  }
});
test('the same public phrases in another route are not automatically reviewed', () => {
  assert.equal(check({ target: 'other/index.html' }).status, 1);
});
test('missing or changed source/hash never permits the exception', () => {
  assert.equal(check({ source: null }).status, 1);
  assert.equal(check({ source: { ...edition, body_markdown: edition.body_markdown + '\nUnreviewed addition.' } }).status, 1);
  assert.equal(check({ html: approvedHtml.replace(edition.content_hash, '0'.repeat(64)) }).status, 1);
});
test('private paths and secrets still fail in a page with reviewed product names', () => {
  const privatePath = ['', 'home', 'private-reviewer', 'private.txt'].join('/');
  for (const value of [privatePath, 'ghp_' + 'a'.repeat(30), 'SECRET="' + 'b'.repeat(20) + '"']) {
    const result = check({ html: approvedHtml + `<p>${value}</p>` });
    assert.equal(result.status, 1);
    assert.ok(!result.stderr.includes(value), 'reports must not print the private value');
  }
});
